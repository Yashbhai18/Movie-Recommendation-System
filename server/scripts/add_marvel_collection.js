async function run() {
  console.log(`Starting Marvel Catalog Integration...`);
  let addedCount = 0;
  let updatedCount = 0;

  for (const item of marvelItems) {
    // 1. Verify / fix poster URL
    let poster = await verifyPoster(item.poster_path);
    if (!poster) {
      console.log(`Searching poster for: ${item.title}...`);
      poster = await searchTmdbPoster(item.title);
    }
    if (poster) {
      item.poster_path = poster;
      item.backdrop_path = poster;
    }

    const key = item.title.toLowerCase().trim();
    const existingIndex = movies.findIndex(m => m.title.toLowerCase().trim() === key);

    if (existingIndex === -1) {
      movies.push(item);
      existingTitles.add(key);
      addedCount++;
    } else {
      // Update with rich metadata if already present
      movies[existingIndex] = {
        ...movies[existingIndex],
        ...item
      };
      updatedCount++;
    }
  }

  // Save curatedMovies.json
  fs.writeFileSync(jsonPath, JSON.stringify(movies, null, 2), 'utf-8');
  console.log(`curatedMovies.json updated! Added: ${addedCount}, Updated: ${updatedCount}. Total catalog size: ${movies.length}`);

  // Save movies.csv
  const csvRows = [
    "title,genres,keywords,director,cast,year,vote_average,runtime,overview,country"
  ];

  for (const m of movies) {
    const t = `"${(m.title || '').replace(/"/g, '""')}"`;
    const g = `"${(m.genres || []).join(' ')}"`;
    const k = `"${(m.keywords || []).join(' ')}"`;
    const d = `"${(m.director || '').replace(/"/g, '""')}"`;
    const c = `"${(m.cast || []).join(' ').replace(/"/g, '""')}"`;
    const y = m.year || 2020;
    const v = m.vote_average || 7.5;
    const r = m.runtime || 120;
    const o = `"${(m.overview || '').replace(/"/g, '""')}"`;
    const country = m.country || 'USA';
    csvRows.push(`${t},${g},${k},${d},${c},${y},${v},${r},${o},${country}`);
  }

  fs.writeFileSync(csvPath, csvRows.join('\n'), 'utf-8');
  console.log(`movies.csv updated with all ${movies.length} titles!`);
}

run();

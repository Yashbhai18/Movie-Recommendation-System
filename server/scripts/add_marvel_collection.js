// Helper to verify URL returns 200 OK
async function verifyPoster(url) {
  if (!url) return null;
  try {
    const res = await fetch(url, { method: 'HEAD' });
    if (res.ok) return url;
  } catch (e) {
    // ignore
  }
  return null;
}

// Fallback search TMDB web if a URL needs resolution
async function searchTmdbPoster(query) {
  try {
    const url = 'https://www.themoviedb.org/search/movie?query=' + encodeURIComponent(query);
    const res = await fetch(url, {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
        'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8'
      }
    });
    if (res.ok) {
      const html = await res.text();
      const match = html.match(/\/t\/p\/[a-zA-Z0-9_]+\/([a-zA-Z0-9_\-\.]+\.(?:jpg|png|webp))/i);
      if (match) {
        const poster = `https://image.tmdb.org/t/p/w500/${match[1]}`;
        const test = await verifyPoster(poster);
        if (test) return poster;
      }
    }
  } catch (e) {
    // ignore
  }
  return null;
}

